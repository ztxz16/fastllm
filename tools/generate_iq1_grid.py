"""Generate/check the capture-safe IQ1 codebook from the canonical GGUF table."""
import argparse
from pathlib import Path
import re


def render(root):
    source = (root / 'third_party/gguf/gguf.h').read_text()
    body = source.split('GGML_TABLE_BEGIN(uint64_t, iq1s_grid, NGRID_IQ1S)', 1)[1].split('GGML_TABLE_END()', 1)[0]
    values = [int(value, 16) for value in re.findall(r'0x[0-9a-fA-F]+', body)]
    if len(values) != 2048:
        raise ValueError('unexpected canonical IQ1 codebook size')
    packed = []
    for value in values:
        result = 0
        for i in range(8):
            signed = (value >> (8*i)) & 255
            if signed >= 128:
                signed -= 256
            if signed not in (-1, 0, 1):
                raise ValueError('unexpected IQ1 codebook value')
            result |= (signed + 1) << (8*(i % 4) + 4*(i // 4))
        packed.append(result)
    text = '''#pragma once
// Copyright (C) 2023-2024 The ggml authors
// Copyright (C) 2024 Iwan Kawrakow
// SPDX-License-Identifier: MIT
// Generated by tools/generate_iq1_grid.py from third_party/gguf/gguf.h.
// Each byte holds values j+1 and j+5 in its low/high nibbles.
// Static storage is immediately usable during CUDA Graph capture.
static const __device__ uint32_t fastllm_iq1_grid_packed[2048] = {
'''
    text += ''.join('    ' + ', '.join(f'0x{x:08x}u' for x in packed[i:i+8]) + ',\n'
                    for i in range(0, len(packed), 8))
    return text + '};\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    target = root / 'src/devices/cuda/fastllm-gguf-iq1-grid.cuh'
    expected = render(root)
    if args.check:
        if target.read_text() != expected:
            raise SystemExit('IQ1 packed codebook differs; run tools/generate_iq1_grid.py')
        print('PASS: all 2048 IQ1 codebook entries match the canonical table')
    else:
        target.write_text(expected)
