"""后台启动单个验证脚本，独立运行目录保存 PID、完整命令、日志和最终退出码。"""

import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import shlex
import subprocess
import sys
import uuid

ROOT = Path(__file__).resolve().parents[3]


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "--supervise":
        directory = Path(sys.argv[2])
        command = json.loads((directory / "command.json").read_text())
        code = 1
        try:
            child = subprocess.Popen(command, cwd=ROOT)
            (directory / "test.pid").write_text(str(child.pid) + "\n")
            code = child.wait()
        finally:
            (directory / "exit_code").write_text(str(code) + "\n")
        return code
    parser = argparse.ArgumentParser()
    parser.add_argument("phase", choices=("protocol", "router", "generation", "lifecycle", "ipc", "performance"))
    parser.add_argument("args", nargs=argparse.REMAINDER)
    args = parser.parse_args()
    name = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ") + "_pd_" + args.phase + "_" + uuid.uuid4().hex[:8]
    directory = ROOT / "test/distributed/results" / name
    directory.mkdir(parents=True, exist_ok=False)
    extra = args.args[1:] if args.args[:1] == ["--"] else args.args
    if "--output" in extra or any(a.startswith("--output=") for a in extra):
        parser.error("output directory is generated by the launcher")
    command = [sys.executable, str(Path(__file__).with_name("check_" + args.phase + ".py")),
               "--output", str(directory), *extra]
    (directory / "command.json").write_text(json.dumps(command, ensure_ascii=False))
    (directory / "command.txt").write_text(shlex.join(command) + "\n")
    with (directory / "stdout.log").open("wb") as out, (directory / "stderr.log").open("wb") as err:
        process = subprocess.Popen([sys.executable, str(Path(__file__).resolve()), "--supervise", str(directory)],
            cwd=ROOT, stdin=subprocess.DEVNULL, stdout=out, stderr=err, start_new_session=True)
    (directory / "supervisor.pid").write_text(str(process.pid) + "\n")
    print(json.dumps(dict(directory=str(directory), supervisor_pid=process.pid,
                         status="started; inspect exit_code and summary after completion"), ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
