"""Generate native Unicode properties from the reference tokenizer's regex engine.

Run with the tokenizers version used to validate the checkpoint, for example:
  python test/tools/generate_unicode_categories.py src/unicode-categories.inc
Python's unicodedata may use an older Unicode version than tokenizers.Regex.
"""
import sys
from pathlib import Path
import tokenizers
from tokenizers import Regex, pre_tokenizers

chars = ''.join(chr(c) for c in range(0x110000) if not 0xd800 <= c <= 0xdfff)
masks = bytearray(0x110001)
for category, bit in {"L": 1, "M": 2, "N": 4, "P": 8, "S": 16}.items():
    splitter = pre_tokenizers.Split(Regex(r'\p{' + category + r'}+'), behavior='removed')
    matches = bytearray(b'\1') * len(chars)
    for _, (start, end) in splitter.pre_tokenize_str(chars):
        matches[start:end] = b'\0' * (end-start)
    for i, match in enumerate(matches):
        if match:
            masks[ord(chars[i])] |= bit

ranges = []
start = previous = 0
for code, kind in enumerate(masks):
    if kind != previous:
        if previous:
            ranges.append((start, code-1, previous))
        start, previous = code, kind
Path(sys.argv[1]).write_text(
    '// Generated by test/tools/generate_unicode_categories.py; tokenizers ' +
    tokenizers.__version__ + ' Regex Unicode properties.\n' +
    '// L=1, M=2, N=4, P=8, S=16. Other categories have mask 0.\n' +
    ''.join('{0x%x, 0x%x, %d},\n' % row for row in ranges))
