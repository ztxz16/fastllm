"""Generate dependency-free canonical Unicode normalization tables."""
from pathlib import Path
import unicodedata as u

# Keep regeneration reproducible; newer Python versions carry different tables.
if u.unidata_version != '13.0.0':
    raise SystemExit('Use Python with Unicode 13.0.0 (Python 3.9/3.10) to regenerate these tables.')

root = Path(__file__).resolve().parents[2]
ccc, decomposition, composition = [], [], []
for value in range(0x110000):
    char = chr(value)
    if u.combining(char):
        ccc.append((value, u.combining(char)))
    raw = u.decomposition(char)
    if raw and not raw.startswith('<'):
        parts = [int(x, 16) for x in raw.split()]
        assert 1 <= len(parts) <= 2
        decomposition.append((value, parts[0], parts[1] if len(parts) == 2 else 0))
        if len(parts) == 2 and u.normalize('NFC', ''.join(map(chr, parts))) == char:
            composition.append((parts[0], parts[1], value))
output = [f'// Generated by test/hy_nomas/generate_nfc_tables.py; Unicode {u.unidata_version}.',
          '// Canonical normalization data; Hangul is handled algorithmically.',
          'static constexpr uint32_t nfcCCC[][2] = {']
output += ['{%s},' % ','.join(hex(x) for x in row) for row in ccc]
output += ['};', 'static constexpr uint32_t nfcDecomposition[][3] = {']
output += ['{%s},' % ','.join(hex(x) for x in row) for row in decomposition]
output += ['};', 'static constexpr uint32_t nfcComposition[][3] = {']
output += ['{%s},' % ','.join(hex(x) for x in row) for row in sorted(composition)]
output += ['};']
(root / 'src/models/hy_nomas/nfc_tables.inc').write_text('\n'.join(output) + '\n')
