#!/usr/bin/env bash
# DeepSeek-V4.1 Flash on eight B300 GPUs, with one attention replica per rank.
set -euo pipefail
model=${1:?Usage: serve_deepseek_v41_b300.sh MODEL_PATH}
dspark=${FASTLLM_DSV41_DSPARK:-0}
if [[ "$dspark" != 0 ]]; then
    export FASTLLM_DSV41_VERIFY_PEER_AR="${FASTLLM_DSV41_VERIFY_PEER_AR:-1}"
fi
export CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES:-0,1,2,3,4,5,6,7}"
export FASTLLM_EXECUTION_MODE=gpu
export FASTLLM_CUDA_GRAPH=1
export FASTLLM_DSV41_LOCAL_EP_GRAPH=1
export FASTLLM_DSV41_MEGA_SHARED=1
export FASTLLM_DSV41_SM100_MEGA=1
export FASTLLM_DSV41_DEVICE_POSITIONS=1
export FASTLLM_DSV41_OWNER_EMBEDDING=1
export FASTLLM_DSV41_FLASHMLA=1
export FASTLLM_DSV41_MLA_OUTPUT=1
export FASTLLM_DSV41_MLA_PAGED=1
export FASTLLM_DSV41_CAPTURE_GREEDY=1
export FASTLLM_DSV41_MLA_BF16_ROUND=1
export FASTLLM_DSV41_MLA_HEAD_MAJOR=1
export FASTLLM_DSV41_MLA_EXACT_ATTENTION=0
export FASTLLM_DSV41_MOE_RESERVE_CLUSTER=1
export FASTLLM_DSV41_HC_OVERLAP=1
export FASTLLM_DSV41_HC_TENSOR_OVERLAP=1
export FASTLLM_DSV41_HC_LATE_JOIN=0
export FASTLLM_DSV41_HC_CLUSTER=small
export FASTLLM_DSV41_HC_FLASH_FORK=1
export FASTLLM_DSV41_HC_CLUSTER_PUSH=small
export FASTLLM_DSV41_SHORT_INDEX=1
export FASTLLM_DSV41_PACK_ATTENTION=1
export FASTLLM_DSV41_VECTOR_ROUTER=1
export FASTLLM_DSV41_PUBLISH_GREEDY=1
export FASTLLM_DSV41_EXPERT_BOUNDARY=1
export FASTLLM_DSV41_PACK_QUERY=1
export FASTLLM_DSV41_OWNER_INPUT_PACKET=1
export FASTLLM_DSV41_EARLY_HISTORY=1
export FASTLLM_DSV41_SCALAR_DECODE=1
export FASTLLM_DSV41_PACKET_POSITIONS=1
export FASTLLM_DSV41_SINGLE_CTA_PROJECTIONS=1
export FASTLLM_DSV41_STAGED_HC=small
export FASTLLM_DSV41_TUNED_PROJECTIONS=1
export FASTLLM_DSV41_FORK_COMPRESSOR=1
export FASTLLM_DSV41_DIRECT_QUERY=1
export FASTLLM_DSV41_REGISTER_PULL=1
export FASTLLM_DSV41_SINGLE_HISTOGRAM=1
export FASTLLM_DSV41_FIXED_QNORM=1
export FASTLLM_DSV41_FORK_KEY_NORM=1

# Set the group to 0 to use the original decode implementation on this preset.
boundary=${FASTLLM_DSV41_BOUNDARY_OPT:-1}
export FASTLLM_DSV41_SHORT_PAGES="${FASTLLM_DSV41_SHORT_PAGES:-$boundary}"
export FASTLLM_DSV41_INDEX_PROJECTIONS="${FASTLLM_DSV41_INDEX_PROJECTIONS:-$boundary}"
export FASTLLM_DSV41_SOURCE_PUBLISH="${FASTLLM_DSV41_SOURCE_PUBLISH:-$boundary}"
export FASTLLM_DSV41_EARLY_COMPRESS="${FASTLLM_DSV41_EARLY_COMPRESS:-$boundary}"
export FASTLLM_DSV41_POST_PACKET="${FASTLLM_DSV41_POST_PACKET:-$boundary}"
export FASTLLM_DSV41_DIRECT_ROUTES="${FASTLLM_DSV41_DIRECT_ROUTES:-$boundary}"
export FASTLLM_DSV41_ORDER_WORD="${FASTLLM_DSV41_ORDER_WORD:-$boundary}"
export FASTLLM_DSV41_EARLY_MOE_PACK="${FASTLLM_DSV41_EARLY_MOE_PACK:-$boundary}"

exec "${PYTHON:-python3}" -m ftllm.cli serve "$model" \
  --host 127.0.0.1 --port "${PORT:-18417}" --model_name deepseek-v41-flash-1017 \
  --tp 8 --attn-dp-size 8 --moe_device multicuda:0,1,2,3,4,5,6,7 --ngram_device cuda \
  --atype float32 --kv_cache_dtype fp4_e2m1 --dspark "$dspark" --speculative_dspark_confidence_threshold "${FASTLLM_DSPARK_CONFIDENCE_THRESHOLD:-0}" --no_fast_prefill \
  --max_batch 128 --tokens 131072 --max_context_length 8192 --chunked_prefill_size 2048 \
  --cache_history false --prefix_cache false
